import hashlib
import io

import numpy as np
import streamlit as st
import torch
from PIL import Image, ImageOps
from skimage.metrics import (
    peak_signal_noise_ratio,
    structural_similarity,
)
from streamlit_drawable_canvas import st_canvas
from diffusers import StableDiffusionInpaintPipeline

st.set_page_config(
    page_title="Stable Diffusion Inpainting Comparison",
    layout="wide",
)

WORK_SIZE = 512

MODEL_ID = "sd-legacy/stable-diffusion-inpainting"


@st.cache_resource
def load_pipeline():
    device = (
        "mps"
        if torch.backends.mps.is_available()
        else "cpu"
    )

    pipe = StableDiffusionInpaintPipeline.from_pretrained(
        MODEL_ID,
        torch_dtype=torch.float32,
    )

    pipe = pipe.to(device)
    pipe.set_progress_bar_config(disable=True)

    return pipe, device


def image_to_png(image):
    buffer = io.BytesIO()
    image.save(buffer, format="PNG")
    return buffer.getvalue()


def prepare_image(file_bytes):
    image = ImageOps.exif_transpose(
        Image.open(io.BytesIO(file_bytes))
    ).convert("RGB")

    return image.resize(
        (WORK_SIZE, WORK_SIZE),
        Image.Resampling.LANCZOS,
    )


def calculate_metrics(original, generated, mask=None):
    original_array = np.array(original, dtype=np.uint8)
    generated_array = np.array(generated, dtype=np.uint8)

    if original_array.shape != generated_array.shape:
        raise ValueError(
            "Original and generated images must have the same size."
        )

    if mask is None:
        psnr = peak_signal_noise_ratio(
            original_array,
            generated_array,
            data_range=255,
        )

        ssim = structural_similarity(
            original_array,
            generated_array,
            data_range=255,
            channel_axis=-1,
            win_size=7,
        )

        return float(psnr), float(ssim)

    difference = (
        original_array.astype(np.float64)
        - generated_array.astype(np.float64)
    )

    masked_mse = float(np.mean(
        difference[mask] ** 2
    ))

    masked_psnr = (
        float("inf")
        if masked_mse == 0
        else float(10 * np.log10(
            (255.0 ** 2) / masked_mse
        ))
    )

    return float(masked_psnr), None


st.title("Stable Diffusion Inpainting Comparison")

st.write(
    "Upload the damaged image and the undamaged original. "
    "Paint the damaged area, generate a restoration, "
    "and compare the result with the original."
)

st.subheader("1. Upload the damaged image")

damaged_file = st.file_uploader(
    "Upload damaged image",
    type=["png", "jpg", "jpeg", "webp"],
    key="damaged_image",
)

if damaged_file is None:
    st.info("Upload the damaged image first.")
    st.stop()

damaged_bytes = damaged_file.getvalue()
source = prepare_image(damaged_bytes)

image_hash = hashlib.sha256(damaged_bytes).hexdigest()

st.subheader("2. Upload the undamaged original")

st.caption(
    "This image is used only to calculate PSNR and SSIM "
    "after Stable Diffusion generates the missing area."
)

reference_file = st.file_uploader(
    "Upload undamaged original",
    type=["png", "jpg", "jpeg", "webp"],
    key="original_reference",
)

if reference_file is None:
    st.info(
        "Upload the undamaged original to enable comparison."
    )

reference_ready = reference_file is not None

if reference_ready:
    original_reference = prepare_image(
        reference_file.getvalue()
    )

if st.button("Clear mask"):
    st.session_state["canvas_revision"] = (
        st.session_state.get("canvas_revision", 0) + 1
    )
    st.session_state.pop("result", None)

st.subheader("3. Paint the damaged area")

st.caption(
    "White painted pixels will be regenerated by Stable Diffusion. "
    "Black pixels will be preserved."
)

canvas_result = st_canvas(
    fill_color="rgba(255, 255, 255, 1)",
    stroke_width=30,
    stroke_color="#ffffff",
    background_image=source,
    update_streamlit=True,
    width=WORK_SIZE,
    height=WORK_SIZE,
    drawing_mode="freedraw",
    return_image_data=True,
    key=(
        f"canvas_{image_hash}_"
        f"{st.session_state.get('canvas_revision', 0)}"
    ),
)

drawing = canvas_result.image_data

if drawing is None:
    st.info("Paint the damaged area you want to regenerate.")
    st.stop()

drawing = np.asarray(drawing)
mask = drawing[:, :, 3] > 10

if not np.any(mask):
    st.info("Paint at least one area before running the model.")
    st.stop()

mask_image = Image.fromarray(
    mask.astype(np.uint8) * 255
)

st.write(
    f"Selected area: {100 * float(np.mean(mask)):.2f}% "
    "of the image"
)

prompt = st.text_input(
    "Prompt",
    value=(
        "seamlessly continue the surrounding pattern, "
        "highly detailed, realistic texture"
    ),
)

negative_prompt = st.text_input(
    "Negative prompt",
    value=(
        "blurry, low quality, distorted, extra objects, "
        "text, watermark, artifacts"
    ),
)

steps = st.slider(
    "Inference steps",
    min_value=10,
    max_value=50,
    value=20,
)

guidance_scale = st.slider(
    "Guidance scale",
    min_value=1.0,
    max_value=15.0,
    value=7.5,
    step=0.5,
)

seed = st.number_input(
    "Seed",
    min_value=0,
    value=42,
)

if st.button("Generate and compare", type="primary"):
    if not reference_ready:
        st.error(
            "Upload the undamaged original before generating "
            "and comparing the result."
        )
        st.stop()

    try:
        with st.spinner(
            "Running Stable Diffusion. "
            "This can take several minutes."
        ):
            pipe, device = load_pipeline()

            generator = torch.Generator(device).manual_seed(
                int(seed)
            )

            generated = pipe(
                prompt=prompt,
                negative_prompt=negative_prompt,
                image=source,
                mask_image=mask_image,
                num_inference_steps=int(steps),
                guidance_scale=float(guidance_scale),
                generator=generator,
            ).images[0]

        masked_psnr, _ = calculate_metrics(
            original_reference,
            generated,
            mask,
        )

        full_psnr, full_ssim = calculate_metrics(
            original_reference,
            generated,
        )

        st.session_state["result"] = {
            "source": source,
            "mask": mask_image,
            "generated": generated,
            "reference": original_reference,
            "masked_psnr": masked_psnr,
            "full_psnr": full_psnr,
            "full_ssim": full_ssim,
        }

    except Exception as error:
        st.error(f"Generation failed: {error}")
        st.exception(error)

result = st.session_state.get("result")

if result is None:
    st.stop()

st.header("Result")

left, middle, right = st.columns(3)

with left:
    st.image(
        result["source"],
        caption="Damaged input",
    )

with middle:
    st.image(
        result["mask"],
        caption="Regenerated area",
    )

with right:
    st.image(
        result["generated"],
        caption="Stable Diffusion result",
    )

st.subheader("Comparison with the undamaged original")

first, second, third = st.columns(3)

with first:
    st.metric(
        "Masked PSNR",
        "Infinity"
        if np.isinf(result["masked_psnr"])
        else f"{result['masked_psnr']:.2f} dB",
    )

with second:
    st.metric(
        "Full-image PSNR",
        f"{result['full_psnr']:.2f} dB",
    )

with third:
    st.metric(
        "Full-image SSIM",
        f"{result['full_ssim']:.4f}",
    )

if result["full_ssim"] >= 0.90:
    st.success("Excellent similarity to the original.")
elif result["full_ssim"] >= 0.75:
    st.success("Good similarity to the original.")
elif result["full_ssim"] >= 0.50:
    st.warning("Moderate similarity to the original.")
else:
    st.error("Low similarity to the original.")

st.download_button(
    "Download generated image",
    data=image_to_png(result["generated"]),
    file_name="stable_diffusion_result.png",
    mime="image/png",
)